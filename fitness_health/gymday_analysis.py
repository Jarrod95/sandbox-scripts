"""Read Gym Day / Daily Strength JSON ZIP exports without committing personal data."""
from __future__ import annotations

import json
import zipfile
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path


def load_training(root: Path):
    """Return aggregate workout statistics and per-exercise daily series.

    Export is the ZIP generated by Gym Day/Daily Strength. Timestamps are
    Unix milliseconds; sets are embedded in WorkoutSession.json.
    """
    folder = Path(root) / "gymday" / "data"
    archives = sorted(folder.glob("*.zip"), key=lambda p: p.stat().st_mtime)
    if not archives:
        return {"available": False, "message": "Place a Gym Day export ZIP in fitness_health/gymday/data/", "summary": {}, "exercises": []}
    archive = archives[-1]
    with zipfile.ZipFile(archive) as z:
        if "WorkoutSession.json" not in z.namelist():
            raise ValueError("Gym Day ZIP lacks WorkoutSession.json")
        sessions = json.loads(z.read("WorkoutSession.json"))
    if not isinstance(sessions, list):
        raise ValueError("WorkoutSession.json must contain a list")
    if len(sessions) > 100000:
        raise ValueError("Too many workout sessions")
    per_exercise = defaultdict(lambda: defaultdict(lambda: {"sets": 0, "reps": 0, "volume_kg": 0.0, "max_weight_kg": 0.0, "estimated_1rm_kg": 0.0}))
    workout_dates = set()
    total_sets = 0
    session_count = 0
    for session in sessions:
        if not isinstance(session, dict):
            continue
        stamp = session.get("startDate")
        try:
            date = datetime.fromtimestamp(float(stamp) / 1000, tz=timezone.utc).date().isoformat()
        except (TypeError, ValueError, OverflowError, OSError):
            continue
        workout_dates.add(date)
        session_count += 1
        for entry in session.get("workoutSessionExercises", []) or []:
            exercise = entry.get("exercise") or {}
            name = str(exercise.get("name") or "").strip()
            eid = str(exercise.get("id") or name)
            if not name:
                continue
            for record in entry.get("workoutSessionSets", []) or []:
                if not isinstance(record, dict) or record.get("warmUp") or record.get("isComplete") is False:
                    continue
                try:
                    weight = float(record.get("weight") or 0)
                    reps = int(record.get("reps") or 0)
                except (TypeError, ValueError):
                    continue
                if not (0 <= weight <= 2000 and 0 < reps <= 1000):
                    continue
                unit = str(record.get("measurementUnit") or "kg").lower()
                if unit in ("lb", "lbs"):
                    weight *= 0.45359237
                elif unit not in ("kg", "kgs"):
                    continue
                metric = per_exercise[(eid, name)][date]
                metric["sets"] += 1
                metric["reps"] += reps
                metric["volume_kg"] += weight * reps
                metric["max_weight_kg"] = max(metric["max_weight_kg"], weight)
                if reps <= 12 and weight > 0:
                    metric["estimated_1rm_kg"] = max(metric["estimated_1rm_kg"], weight * (1 + reps / 30))
                total_sets += 1
    exercises = []
    for (eid, name), by_date in per_exercise.items():
        history = [{"date": date, **{k: round(v, 2) if isinstance(v, float) else v for k, v in vals.items()}}
                   for date, vals in sorted(by_date.items())]
        if not history:
            continue
        exercises.append({"id": eid, "name": name, "sessions": len(history),
                          "best_weight_kg": max(x["max_weight_kg"] for x in history),
                          "best_estimated_1rm_kg": max(x["estimated_1rm_kg"] for x in history),
                          "total_volume_kg": round(sum(x["volume_kg"] for x in history), 1),
                          "history": history})
    exercises.sort(key=lambda e: (-e["sessions"], e["name"]))
    return {
        "available": True,
        "file": archive.name,
        "summary": {"workouts": session_count, "training_days": len(workout_dates),
                    "sets": total_sets, "exercises": len(exercises),
                    "first_date": min(workout_dates) if workout_dates else None,
                    "last_date": max(workout_dates) if workout_dates else None},
        "exercises": exercises,
        "methodology": "Completed non-warm-up sets. Volume = kg × reps. e1RM = Epley (1–12 reps only); estimates are not tested maxima. Session dates use UTC; local midnight sessions may shift by one day. Each exercise retains its original ID; machines and free weights are not interchangeable."
    }
